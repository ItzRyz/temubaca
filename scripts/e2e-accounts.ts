/**
 * Create or refresh the two dedicated E2E accounts on the local Supabase stack (or the project in
 * `.env` when `.env.development.local` does not exist).
 *
 *   bun scripts/e2e-accounts.ts
 *
 * Accounts: "E2E Pemilik" (lends) and "E2E Peminjam" (borrows), both email-confirmed MEMBERs.
 * Each run sets a fresh random password and writes the credentials to `.env.e2e`, which is
 * gitignored (`.env*`). The passwords are never printed. Profiles are created on first sign-in.
 */
import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";

import { createClient } from "@supabase/supabase-js";
import { config } from "dotenv";

config({ path: [".env.development.local", ".env.local", ".env"], quiet: true });

const accounts = [
    { key: "OWNER", email: "e2e-pemilik@temubaca.test", displayName: "E2E Pemilik" },
    { key: "BORROWER", email: "e2e-peminjam@temubaca.test", displayName: "E2E Peminjam" },
] as const;

async function main() {
    if (process.env.NODE_ENV === "production") throw new Error("Refusing to run with NODE_ENV=production.");
    const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
    if (!url || !serviceKey) throw new Error("Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY first.");

    const admin = createClient(url, serviceKey, { auth: { autoRefreshToken: false, persistSession: false } });
    const { data, error } = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
    if (error) throw error;

    const lines = ["# Generated by scripts/e2e-accounts.ts. Do not commit."];
    for (const account of accounts) {
        const password = `E2e-${randomBytes(18).toString("base64url")}`;
        const existing = data.users.find((user) => user.email === account.email);
        const attributes = { password, email_confirm: true, user_metadata: { display_name: account.displayName } };
        const result = existing
            ? await admin.auth.admin.updateUserById(existing.id, attributes)
            : await admin.auth.admin.createUser({ email: account.email, ...attributes });
        if (result.error) throw result.error;
        lines.push(`E2E_${account.key}_EMAIL=${account.email}`, `E2E_${account.key}_PASSWORD=${password}`);
        console.log(`${existing ? "updated" : "created"}: ${account.displayName}`);
    }
    await writeFile(".env.e2e", `${lines.join("\n")}\n`);
    console.log("credentials written to .env.e2e");
}

await main();
