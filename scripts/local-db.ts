/**
 * Prepare the local Supabase stack (Docker) for development and E2E:
 *
 *   bunx supabase start      # once per boot; ports 556xx (see supabase/config.toml)
 *   bun run db:local         # this script
 *
 * 1. Writes `.env.development.local` from `supabase status`. Next dev and the scripts read it before
 *    `.env`, so local work never touches the cloud project (production since DEC-01).
 * 2. Applies the Drizzle migrations, then supabase/migrations (the auth trigger needs the tables).
 * 3. Copies the public `books` catalog from the cloud project (`--no-books` skips it). No accounts,
 *    listings, or other personal data are copied.
 */
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";

import { parse } from "dotenv";
import { Pool } from "pg";

const LOCAL_ENV = ".env.development.local";

function supabaseStatus() {
    const result = spawnSync("bunx", ["supabase", "status", "-o", "env"], { encoding: "utf8", shell: true });
    if (result.status !== 0) throw new Error("Local Supabase is not running. Start it with `bunx supabase start`.");
    return parse(result.stdout);
}

function isLocal(url: string) {
    return ["127.0.0.1", "localhost"].includes(new URL(url).hostname);
}

async function writeLocalEnv(status: Record<string, string>) {
    const values = {
        NEXT_PUBLIC_APP_URL: "http://localhost:3000",
        NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
        NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY ?? status.ANON_KEY,
        SUPABASE_SERVICE_ROLE_KEY: status.SECRET_KEY ?? status.SERVICE_ROLE_KEY,
        DATABASE_URL: status.DB_URL,
        DIRECT_URL: status.DB_URL,
    };
    for (const [name, value] of Object.entries(values)) if (!value) throw new Error(`supabase status did not return a value for ${name}.`);
    if (!isLocal(values.DATABASE_URL)) throw new Error("supabase status returned a non-local database URL.");
    const lines = ["# Generated by scripts/local-db.ts for the local Supabase stack. Do not commit.", ...Object.entries(values).map(([k, v]) => `${k}=${v}`)];
    await writeFile(LOCAL_ENV, `${lines.join("\n")}\n`);
    console.log(`wrote ${LOCAL_ENV}`);
    return values;
}

async function applySupabaseMigrations(databaseUrl: string) {
    const files = (await readdir("supabase/migrations")).filter((file) => file.endsWith(".sql")).sort();
    const pool = new Pool({ connectionString: databaseUrl, max: 1 });
    try {
        for (const file of files) {
            await pool.query(await readFile(`supabase/migrations/${file}`, "utf8"));
            console.log(`applied supabase/migrations/${file}`);
        }
    } finally {
        await pool.end();
    }
}

async function copyBooks(localUrl: string) {
    const cloudUrl = existsSync(".env") ? parse(await readFile(".env")).DATABASE_URL : undefined;
    if (!cloudUrl) {
        console.log("skip books: no DATABASE_URL in .env");
        return;
    }
    const cloud = new Pool({ connectionString: cloudUrl, max: 1 });
    const local = new Pool({ connectionString: localUrl, max: 1 });
    try {
        const rows = (await cloud.query(`select * from books`)).rows;
        const inserted = await local.query(
            `insert into books select * from json_populate_recordset(null::books, $1::json) on conflict (id) do nothing`,
            [JSON.stringify(rows)],
        );
        console.log(`books: ${rows.length} in cloud, ${inserted.rowCount ?? 0} new locally`);
    } finally {
        await Promise.all([cloud.end(), local.end()]);
    }
}

async function main() {
    const env = await writeLocalEnv(supabaseStatus());

    const migrate = spawnSync("bun", ["scripts/migrate-dev.ts", "--apply"], { stdio: "inherit", shell: true });
    if (migrate.status !== 0) throw new Error("Drizzle migrations failed.");

    await applySupabaseMigrations(env.DATABASE_URL);
    if (!process.argv.includes("--no-books")) await copyBooks(env.DATABASE_URL);
}

main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
});
